-- Bit helpers (SAM relies on 8-bit bitwise ops; kept portable across LuaJIT/Lua 5.x).
local band, bor, bxor
local ok, bit = pcall(require, "bit")
if ok and type(bit) == "table" and bit.band then
    band, bor, bxor = bit.band, bit.bor, bit.bxor
else
    local ok2, bit32 = pcall(require, "bit32")
    if ok2 and type(bit32) == "table" and bit32.band then
        band, bor, bxor = bit32.band, bit32.bor, bit32.bxor
    else
        local mul = { 1, 2, 4, 8, 16, 32, 64, 128 }
        local function tobits(a)
            local r = {}
            for i = 1, 8 do r[i] = (a % (mul[i] * 2)) >= mul[i] end
            return r
        end
        local function frombits(bits)
            local r = 0
            for i = 1, 8 do if bits[i] then r = r + mul[i] end end
            return r
        end
        local function bandImpl(a, b)
            local ab, bb = tobits(a), tobits(b)
            for i = 1, 8 do ab[i] = ab[i] and bb[i] end
            return frombits(ab)
        end
        local function borImpl(a, b)
            local ab, bb = tobits(a), tobits(b)
            for i = 1, 8 do ab[i] = ab[i] or bb[i] end
            return frombits(ab)
        end
        local function bxorImpl(a, b)
            local ab, bb = tobits(a), tobits(b)
            for i = 1, 8 do ab[i] = ab[i] ~= bb[i] end
            return frombits(ab)
        end
        band, bor, bxor = bandImpl, borImpl, bxorImpl
    end
end
M.band = band
M.bor = bor
M.bxor = bxor

return M

